"""Finite author-side checks for the affine quotient and generating-rank proposal.
Build all left/right translations as permutations. Enumerate congruences by
closing equivalence relations under those permutations; never assume that a
kernel is vertical or linear. All public-code computations are over F3.
"""
from itertools import product,combinations

def build(modpoly,p=3,number=1):
    d=len(modpoly)-1;q=p**d;V=q**number
    xy=list(product(range(p),repeat=d))
    # Digits in ascending power order; absolute index of 1 is 1.
    def digits(v,n):return [(v//p**i)%p for i in range(n)]
    def code(v):return sum(x%p*p**i for i,x in enumerate(v))
    def mult(x,y):
        a,b=digits(x,d),digits(y,d);c=[0]*(2*d-1)
        for i in range(d):
            for j in range(d):c[i+j]+=a[i]*b[j]
        for i in range(2*d-2,d-1,-1):
            u=c[i];c[i]=0
            for j in range(d):c[i-d+j]-=u*modpoly[j]
        return code(c[:d])
    def add(x,y):return code([a+b for a,b in zip(digits(x,d),digits(y,d))])
    def spl(v):return [(v//q**j)%q for j in range(number)]
    addv=[[sum(add(a,b)*q**i for i,(a,b) in enumerate(zip(spl(x),spl(y)))) for y in range(V)] for x in range(V)]
    ff=[add(1,mult(i,p)) for i in range(p)]
    fi=[next(j for j in range(q) if mult(j,x)==1) for x in ff]
    scales=[[mult(ff[(i+2*j)%p],fi[i]) for j in range(p)] for i in range(p)]
    mv=lambda c,x:sum(mult(c,a)*q**j for j,a in enumerate(spl(x)))
    sc={(i,j):[mv(scales[i][j],x) for x in range(V)] for i in range(p) for j in range(p)}
    rows=tuple(tuple(((i+j)%p)*V+addv[v][sc[i,j][u]] for j in range(p) for v in range(V)) for i in range(p) for u in range(V))
    assert all(len(set(r))==p*V for r in list(rows)+list(zip(*rows)))
    return rows,V

def congruences(rows):
    n=len(rows);per=rows+tuple(zip(*rows))
    def block(K,x):
        A=list(range(n));queued=[]
        def root(i):
            while A[i]!=i:
                A[i]=A[A[i]];i=A[i]
            return i
        def link(i,j):
            i,j=root(i),root(j)
            if i==j:return
            A[max(i,j)]=min(i,j);queued.append((i,j))
        for k in K:link(0,k)
        link(0,x)
        for i,j in queued:
            for g in per:link(g[i],g[j])
        return frozenset(i for i in range(n) if root(i)==root(0))
    # Each block system generated by successive identifications zero ~ x is
    # found. Multiplication translations generate a transitive permutation group.
    known={frozenset({0})};stack=list(known)
    while stack:
        k=stack.pop()
        for x in range(n):
            if x not in k:
                b=block(k,x)
                if b not in known:known.add(b);stack.append(b)
    return known

def close(rows,seeds):
    a={0};queue=[0]
    def put(x):
        if x not in a:a.add(x);queue.append(x)
    for x in seeds:put(x)
    for x in queue:
        for y in tuple(a):put(rows[x][y]);put(rows[y][x])
    return a

def t_adic(d):
    r,v=build([0]*d+[1]);K=congruences(r);V={x for x in range(v)}
    expected={frozenset(x for x in V if x%(3**i)==0) for i in range(d+1)}
    # Preimages of the genuine lines in the plane modulo (t), using the
    # literal cosets in first coordinate and scalar constant term.
    expected.update(frozenset(i*v+x for i in range(3) for x in V if x%3==a*i%3) for a in range(3))
    expected.add(frozenset(range(3*v)))
    assert K==expected
    print('t^'+str(d),'native order',len(r),'kernel orders',sorted(map(len,K)))
for d in (2,3):t_adic(d)
r,v=build([1,0,1]);k=congruences(r)
assert k=={frozenset([0]),frozenset(range(v)),frozenset(range(3*v))}
print('irreducible t^2+1 native kernel orders',sorted(map(len,k)))
r,v=build([1,0,1],number=2);q=9
# One repeated irreducible block. Test every pair (a,b) after normalizing one
# generator to (1,s) and using the cyclic-section shear to make s=0; every
# independent choice of a vertical adjustment is still a literal native point.
z=v;orders={len(close(r,[z,x])) for x in range(3*v)}
assert orders=={3,27} and len(close(r,[z,1,q]))==243
# Check the affine conjugacy itself for every shift and table pair on the
# smaller irreducible case, not just abstract matrix similarity.
rr,vv=build([1,0,1]);n=len(rr)
for c in range(vv):
    cy=vv+c;s_i=[0,cy,rr[cy][cy]]
    u=tuple(rr[s_i[x//vv]][x%vv] for x in range(n))
    assert len(set(u))==n
    assert all(u[rr[x][y]]==rr[u[x]][u[y]] for x in range(n) for y in range(n))
print('repeated irreducible: normalized two-generator orders',sorted(orders),'three explicit generators',243,'; all 9 shift gauges on 27 points checked')
