#!/usr/bin/env python3
"""Test a normalized 2-cocycle extension exported by verify_s5_v6_h2."""
import json
import subprocess
import sys
import tempfile
from pathlib import Path
from bol_engine import Loop, _atkinson_is_primitive_raw
with tempfile.TemporaryDirectory(prefix='bruck-s5-v6-') as tmpdir:
 path = Path(tmpdir) / 'cocycle.json'
 subprocess.run([sys.executable, str(Path(__file__).with_name('verify_s5_v6_h2.py')), '--json', str(path)], check=True)
 with path.open() as stream:
  data=json.load(stream)
perms=[tuple(g) for g in data['perms']]; A=[tuple(m) for m in data['matrices']];F=data['cocycle'];size=len(perms); assert size==120
I=tuple(range(6)); assert perms[0]==I
ix={g:i for i,g in enumerate(perms)}
def pmul(a,b):return tuple(a[b[i]] for i in range(6))
G=[[ix[pmul(a,b)] for b in perms] for a in perms]; inv=[ix[tuple(g.index(i) for i in range(6))] for g in perms]
def ma(m,v):
 r=0
 for j in range(6):
  if v>>j&1:r^=m[j]
 return r
def gm(x,y):
 g,v=x;h,w=y
 return (G[g][h],v^ma(A[g],w)^F[g][h])
def gi(x):
 g,v=x; h=inv[g]
 return (h,ma(A[h],v^F[g][h]))
def powr(x,n):
 y=(0,0)
 for _ in range(n):y=gm(y,x)
 return y
def conj(x,y):return gm(gm(x,y),gi(x))
# Verify normalized cocycle and associativity for all 120^3 group triples in vector-valued form.
assert all(F[0][g]==F[g][0]==0 for g in range(size))
for g in range(size):
 for h in range(size):
  gh=G[g][h]
  for k in range(size):
   assert ma(A[g],F[h][k])^F[gh][k]^F[g][G[h][k]]^F[g][h]==0
print('global cocycle verified',flush=True)
def ordgroup(i):
 j=i;n=1
 while j: j=G[j][i];n+=1
 return n
pidx=next(i for i in range(size) if ordgroup(i)==5)
p=(pidx,0); fifth=powr(p,5);assert fifth[0]==0
p=(pidx,fifth[1]);assert powr(p,5)==(0,0)
P={powr(p,i) for i in range(5)}
H=[(g,v) for g in range(size) for v in range(64) if conj((g,v),p) in P]
assert len(H)==80
W={v for g,v in H if g==0}; assert len(W)==4
M={v for v in range(32) if bin(v).count('1')%2==0};assert len(M)==16 and M.isdisjoint(W-{0})
cidx=ix[(1,0,3,2,5,4)]
T={G[G[g][cidx]][inv[g]] for g in range(size)};assert len(T)==10
K=[(0,v) for v in sorted(M)]+[(g,v) for g in sorted(T) for v in range(64) if gm((g,v),(g,v))==(0,0)]
assert len(K)==96 and len(set(K))==96
print('sizes G H W K',7680,len(H),len(W),len(K),flush=True)
# Core-free: V subgroup core must be an S5-submodule in W, and F20 is core-free in S5.
assert all(not all(ma(a,v) in W for a in A) for v in W-{0})
print('core-free from W and quotient',flush=True)
# K-invariance by lifts of c,d and a basis of V implies K invariant under its generated group.
Kset=set(K); didx=ix[(0,2,3,4,1,5)]
gens=[(cidx,0),(didx,0)]+[(0,1<<i) for i in range(6)]
assert all(conj(g,k) in Kset for g in gens for k in K)
print('K conjugacy invariance verified',flush=True)
seen={(0,0)}; queue=[(0,0)]
for x in queue:
 for k in K:
  y=gm(x,k)
  if y not in seen:seen.add(y);queue.append(y)
print('group generated by K',len(seen),flush=True)
radical={v for g,v in seen if g==0}; print('generated radical order',len(radical),'equals J',radical==set(range(32)),flush=True)
assert len(seen)==3840 and radical==set(range(32))
print('generated H size',sum(h in seen for h in H),flush=True)
# Left folder a*b in (ab H)∩K: K is invariant, so one transversal verifies every conjugate.
cosets={}
for i,k in enumerate(K):
 for h in H:
  x=gm(k,h)
  if x in cosets:
   print('TRANSVERSAL FAILURE indices',cosets[x],i,'first_section',K[cosets[x]],'second_section',k,'H_witness',gm(gi(K[cosets[x]]),k),flush=True)
   sys.exit(0)
  cosets[x]=i
assert len(cosets)==7680
print('folder transversality verified',flush=True)
assert K[0]==(0,0)
table=[[cosets[gm(a,b)] for b in K] for a in K]
Q=Loop(table,name='w2_v6_candidate_opposite')
print('left Bol',Q.check_left_bol(),flush=True)
primitive=_atkinson_is_primitive_raw(96,list(Q.L[1:])+list(Q.R[1:])); print('multiplication primitive',primitive,flush=True)
for i in range(1,96):
 roots=Q.minimal_congruence_roots(i);n=sum(r==roots[0] for r in roots)
 if 1<n<96:
  print('proper congruence',i,n,Q.verify_is_loop_congruence(roots),flush=True);break
else: print('all single-element congruence closures universal',flush=True)
