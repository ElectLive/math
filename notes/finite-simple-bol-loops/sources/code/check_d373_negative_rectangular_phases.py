from itertools import permutations,product
from collections import deque,Counter

def comp(a,b):return tuple(a[x] for x in b)
def inv(a):return tuple(a.index(i) for i in range(len(a)))
def group(gs):
    e=tuple(range(len(gs[0])));H={e};Q=deque([e])
    while Q:
        z=Q.popleft()
        for g in gs:
            v=comp(g,z)
            if v not in H:H.add(v);Q.append(v)
    return H
ct=Counter()
for m in (2,3):
    X=tuple(range(m));Y=tuple(range(m,2*m));P=tuple(product(X,Y))
    shift=tuple(i//m*m+(i+1)%m for i in X+Y)
    for ra,rb in product(permutations(Y),permutations(X)):
        r=tuple(ra+rb);G=group([shift,r]);H={g for g in G if g[0] in X}
        Or=[];remaining=set(P)
        while remaining:
            x,y=min(remaining);V=frozenset((g[x],g[y]) for g in H);Or.append(V);remaining-=V
        ct['flat' if len(Or)==1 else 'nonflat']+=1
        if len(Or)==1:continue
        def rev(V):return frozenset((r[y],r[x]) for x,y in V)
        modes=[];ac=set(range(len(Or)))
        while ac:
            i=min(ac);j=Or.index(rev(Or[i]));assert rev(Or[j])==Or[i]
            ac-={i,j}
            if i!=j:modes.append((-1,{p:(1 if p in Or[i] else -1 if p in Or[j] else 0) for p in P}))
            V=Or[i]|Or[j]
            if len(V)!=m*m:modes.append((1,{p:(m*m if p in V else 0)-len(V) for p in P}))
        assert modes
        if all(s==-1 for s,f in modes):ct['only minus possible']+=1
        for eps,f in modes:
            assert all(sum(f[x,y] for y in Y)==0 for x in X) and all(sum(f[x,y] for x in X)==0 for y in Y)
            norm=sum(t*t for t in f.values())
            for g in G-H:
                n=inv(g);a=[(f[x,g[y]],f[y,n[x]]) for x,y in product(X,repeat=2)]
                assert all(s==eps*t for s,t in a) and sum(s*t for s,t in a)==eps*norm
                ct['reciprocal arrow tests']+=1
assert ct['only minus possible'] and ct['flat']
print('all paired transitive fiber models m=2,3 generated by arbitrary swap and shared cyclic shift:',dict(ct))
# The 4-cycle has two colors of size 2. Its sole nonconstant centered orbital relation is antisymmetric
# under swapped orientation. Each color-changing arrow squares to a nontrivial inner flip: no fixed site.
def pairings(S):
    if not S:yield [];return
    a=S[0]
    for b in S[1:]:
        for pairs in pairings([x for x in S if x not in (a,b)]):yield [(a,b)]+pairs
