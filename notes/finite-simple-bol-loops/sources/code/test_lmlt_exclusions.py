def involution_class_size_sm(m: int, k: int) -> int:
    """Size of class C_k of cycle type 2^k 1^{m-2k} in S_m."""
    if k < 0 or 2 * k > m:
        return 0
    return math.factorial(m) // ((1 << k) * math.factorial(k) * math.factorial(m - 2 * k))


def total_involutions_and_id_sm(m: int) -> int:
    """I(m) = sum_{k=0}^{floor(m/2)} |C_k|."""
    return sum(involution_class_size_sm(m, k) for k in range(m // 2 + 1))


def is_prime(n: int) -> bool:
    if n < 2:
        return False
    if n % 2 == 0:
        return n == 2
    d = 3
    while d * d <= n:
        if n % d == 0:
            return False
        d += 2
    return True


def lemma_9_5_dagger_bound(m: int, use_3_for_c34: bool = False) -> int:
    """Certified integer upper bound on the RHS of Lemma 9.5 (dagger) over all
    integers a, b, c_2, c_34 >= 0 with a + b + c_2 + c_34 = m and c_2 even,
    using exact integer 4th-root ceilings ceil(24^{c_34 / 4}) with zero float error.
    """
    best = 0
    fact = [math.factorial(i) for i in range(m + 1)]
    ceil_24_q: List[int] = []
    for c in range(m + 1):
        target = 24**c
        z = math.isqrt(math.isqrt(target))
        while z**4 < target:
            z += 1
        ceil_24_q.append(z)

    for c2 in range(0, m + 1, 2):
        rem1 = m - c2
        f_c2 = fact[c2 // 2]
        for a in range(rem1 + 1):
            rem2 = rem1 - a
            fa = fact[a // 2] * fact[a // 5]
            exp2_base = (a // 5) + (c2 // 2)
            for b in range(rem2 + 1):
                c34 = rem2 - b
                exp2 = 1 + exp2_base + 2 * b
                c34_factor = (3**c34) if use_3_for_c34 else ceil_24_q[c34]
                val = (1 << exp2) * c34_factor * fa * fact[b // 5] * f_c2 * fact[c34 // 3]
                if val > best:
                    best = val
    return best


def lemma_9_6_sylow2_cap(m: int, k_max: int) -> int:
    """Upper bound on |H cap A_m|_2 when H cap (C_2 cup ... cup C_{2 k_max}) = empty."""
    min_supp = 4 * k_max + 4
    cap = 1
    for u in range(min_supp, m + 1):
        cap *= 1 << (u.bit_length() - 1)
    return cap


def lemma_9_7_jordan_bochert_passes(m: int, h_ord: int) -> bool:
    """Return True if no prime p in (m/2, m-3] dividing `h_ord` violates Jordan-Bochert."""
    for p in range(m // 2 + 1, m - 2):
        if is_prime(p) and h_ord % p == 0:
            max_jb = max(
                (math.factorial(d) // math.factorial((d + 1) // 2)) * math.factorial(m - d)
                for d in range(p, min(m, p + 2) + 1)
            )
            if h_ord > max_jb:
                return False
    return True


def sylow_large_prime_compatible_in_sm(m: int, h_ord: int) -> bool:
    """Necessary Sylow condition for existence of H <= S_m of order `h_ord`:
    for any prime p > m/2 dividing `h_ord`, P in Syl_p(H) has order p (generated by a p-cycle),
    and |N_{S_m}(P)| = p * (p - 1) * (m - p)!. Thus there must exist n_p | (h_ord // p)
    with n_p == 1 (mod p) and (h_ord // n_p) dividing p * (p - 1) * (m - p)!.
    """
    for p in range(m // 2 + 1, m + 1):
        if is_prime(p) and h_ord % p == 0:
            if (h_ord // p) % p == 0:
                return False
            r = h_ord // p
            norm_sm = p * (p - 1) * math.factorial(m - p)
            ok = False
            for np_cand in range(1, r + 1):
                if r % np_cand == 0 and np_cand % p == 1:
                    nh_ord = h_ord // np_cand
                    if norm_sm % nh_ord == 0:
                        ok = True
                        break
            if not ok:
                return False
    return True


def verify_group_has_no_bol_folder_via_lambda2(
    deg: int,
    g_gens: Sequence[Perm],
    aut_gens: Sequence[Perm],
    label: str,
) -> int:
    """Given G = <g_gens> normal in A = <g_gens, aut_gens> <= Sym(deg), exhaustively test all
    involutory cosets t G <= A and all <G, t>-invariant unions Lambda of involutions in t G:
    verify ZERO valid Bol folders exist with <tau * Lambda> = G and |K| > 2.
    Returns the number of generating divisibility-passing unions tested.
    """
    id_p = identity_perm(deg)
    g_pg = PermGroup(deg, g_gens, allow_jordan_fastpath=False)
    g_list = g_pg.enumerate_elements()
    g_set = set(g_list)
    g_ord = len(g_list)

    a_pg = PermGroup(deg, list(g_gens) + list(aut_gens), allow_jordan_fastpath=False)
    a_elems = a_pg.enumerate_elements()
    invs_and_id = [x for x in a_elems if compose(x, x) == id_p]

    coset_reps: List[Perm] = []
    for t in invs_and_id:
        if not any(compose(invert(t), r) in g_set for r in coset_reps):
            coset_reps.append(t)

    tested = 0
    for t in coset_reps:
        coset_invs = [x for x in invs_and_id if compose(invert(t), x) in g_set]
        conj_gens = list(g_gens) + ([t] if t != id_p else [])
        conj_gens_inv = [invert(u) for u in conj_gens]

        def split_orbits(pool: Sequence[Perm]) -> List[List[Perm]]:
            rem_s = set(pool)
            orbs: List[List[Perm]] = []
            while rem_s:
                seed = next(iter(rem_s))
                orb = {seed}
                queue = [seed]
                while queue:
                    cur = queue.pop()
                    for u, ui in zip(conj_gens, conj_gens_inv):
                        conj = compose(u, compose(cur, ui))
                        if conj not in orb:
                            orb.add(conj)
                            queue.append(conj)
                rem_s -= orb
                orbs.append(list(orb))
            return orbs

        classes = split_orbits(coset_invs)
        g_orbits = split_orbits(g_list)
        nc = len(classes)
        for mask in range(1, 1 << nc):
            lam = [x for i in range(nc) if (mask >> i) & 1 for x in classes[i]]
            lam_sz = len(lam)
            if lam_sz <= 2 or lam_sz >= g_ord or g_ord % lam_sz != 0:
                continue
            tau = lam[0]

            # Fast exact generation check <tau * Lambda> == G via incremental BFS
            reached = {id_p}
            gen_used: List[Perm] = []
            for x in lam:
                k = compose(tau, x)
                if k in reached:
                    continue
                gen_used.append(k)
                new_f = [compose(r, k) for r in reached if compose(r, k) not in reached]
                reached.update(new_f)
                q_bfs = list(new_f)
                while q_bfs:
                    cur = q_bfs.pop()
                    for g_u in gen_used:
                        nxt = compose(cur, g_u)
                        if nxt not in reached:
                            reached.add(nxt)
                            q_bfs.append(nxt)
                if len(reached) == g_ord:
                    break
            if len(reached) != g_ord:
                continue

            tested += 1
            h_ord = g_ord // lam_sz

            # Since Lambda^2 is <G, t>-conjugation invariant and every x in Lambda satisfies x^2 = 1,
            # rep in Lambda^2 <=> exists x in Lambda with x * rep in Lambda.
            lam_set = set(lam)
            allowed_orbs: List[List[Perm]] = []
            allowed_sz = 0
            for g_orb in g_orbits:
                rep = g_orb[0]
                if rep == id_p or not any(compose(x, rep) in lam_set for x in lam):
                    allowed_orbs.append(g_orb)
                    allowed_sz += len(g_orb)
            if allowed_sz < h_ord:
                continue

            # Cauchy check on prime divisors of h_ord using orbit representatives
            ok_cauchy = True
            tmp_h = h_ord
            p = 2
            prime_divs: List[int] = []
            while p * p <= tmp_h:
                if tmp_h % p == 0:
                    prime_divs.append(p)
                    while tmp_h % p == 0:
                        tmp_h //= p
                p += 1
            if tmp_h > 1:
                prime_divs.append(tmp_h)

            for pd in prime_divs:
                has_pd = False
                for g_orb in allowed_orbs:
                    rep = g_orb[0]
                    if rep == id_p:
                        continue
                    gp = rep
                    for _ in range(pd - 1):
                        gp = compose(gp, rep)
                    if gp == id_p:
                        has_pd = True
                        break
                if not has_pd:
                    ok_cauchy = False
                    break
            if not ok_cauchy:
                continue

            # If Cauchy still passes (e.g. S_6 with |Lambda|=16, h=45), verify no subgroup of
            # `allowed` of order `h_ord` exists. Since <G, t> normalizes G and preserves `allowed`,
            # any subgroup H <= G of order `h_ord` inside `allowed` can be <G, t>-conjugated to
            # contain `g_orb[0]` for some orbit of prime order `p_max = max(prime_divs)`.
            allowed_set = {g for g_orb in allowed_orbs for g in g_orb}
            valid_elements: List[Perm] = []
            p_max = prime_divs[-1]
            seed_reps: List[Tuple[Perm, Set[Perm]]] = []
            for g_orb in allowed_orbs:
                rep = g_orb[0]
                cyc: List[Perm] = [id_p]
                cur = rep
                while cur != id_p:
                    cyc.append(cur)
                    cur = compose(cur, rep)
                if h_ord % len(cyc) == 0 and all(c in allowed_set for c in cyc):
                    valid_elements.extend(g_orb)
                    if len(cyc) == p_max:
                        seed_reps.append((rep, set(cyc)))
            if len(valid_elements) < h_ord or not seed_reps:
                continue

            def close_subgroup_in_allowed(gens: Sequence[Perm], base_set: Set[Perm], cand: Perm) -> Set[Perm] | None:
                clo = set(base_set)
                clo.add(cand)
                if len(clo) > h_ord:
                    return None
                all_gens = list(gens) + [cand]
                queue_c = list(clo)
                while queue_c:
                    u = queue_c.pop()
                    for g_gen in all_gens:
                        v = compose(u, g_gen)
                        if v not in clo:
                            if v not in allowed_set or len(clo) + 1 > h_ord:
                                return None
                            clo.add(v)
                            queue_c.append(v)
                return clo if (h_ord % len(clo) == 0) else None

            def has_subgroup(cur_gens: List[Perm], cur_set: Set[Perm], start_i: int) -> bool:
                if len(cur_set) == h_ord:
                    return True
                for idx in range(start_i, len(valid_elements)):
                    cand = valid_elements[idx]
                    if cand in cur_set:
                        continue
                    nxt_set = close_subgroup_in_allowed(cur_gens, cur_set, cand)
                    if nxt_set is not None and has_subgroup(cur_gens + [cand], nxt_set, idx + 1):
                        return True
                return False

            if any(has_subgroup([s_rep], s_set, 0) for s_rep, s_set in seed_reps):
                raise AssertionError(f"Found unexpected Bol folder candidate in {label}: h={h_ord}")

    return tested


def verify_am_sm_small_degrees_5_to_8() -> Dict[str, int]:
    """Verify zero valid Lambda subsets exist for A_m and S_m across m in {5, 6, 7, 8}
    under standard Aut = S_m.
    """
    div_hits = 0
    for m in (5, 6, 7, 8):
        max_k = m // 2
        sizes = [involution_class_size_sm(m, k) for k in range(max_k + 1)]
        for g_kind in ("A_m", "S_m"):
            g_ord = math.factorial(m) // (2 if g_kind == "A_m" else 1)
            for mask in range(1, 1 << (max_k + 1)):
                ks = [k for k in range(max_k + 1) if (mask >> k) & 1]
                k_max = max(ks)
                if k_max == 0:
                    continue
                parities = {k % 2 for k in ks}
                if g_kind == "A_m" and len(parities) != 1:
                    continue
                if g_kind == "S_m" and len(parities) != 2:
                    continue
                lam_sz = sum(sizes[k] for k in ks)
                if lam_sz <= 2 or lam_sz >= g_ord or g_ord % lam_sz != 0:
                    continue
                div_hits += 1
                h_ord = g_ord // lam_sz

                # 1. Sylow-2 obstruction (Regime I k_max >= floor(m/4) forbids all Inv(A_m);
                #    otherwise Lemma 9.6 caps |H cap A_m|_2)
                forbids_all_even_inv = (m // 4 >= 1) and (k_max >= m // 4)
                h_am_max_2 = 1 if forbids_all_even_inv else lemma_9_6_sylow2_cap(m, k_max)
                if g_kind == "S_m" and (0 in ks) and (1 in ks):
                    # C_1 = C_0 * C_1 <= Lambda^2 forbids transpositions too; at m <= 5 that kills all odd involutions!
                    if m == 5:
                        h_max_2 = h_am_max_2
                    else:
                        h_max_2 = h_am_max_2 * 2
                else:
                    h_max_2 = h_am_max_2 * (2 if g_kind == "S_m" else 1)
                if (h_ord & -h_ord) > h_max_2:
                    continue

                # 2. If 2 * k_max + 1 <= m, C_{(3)} <= C_{k_max}^2 <= Lambda^2:
                #    at m = 5, S_5 has NO other elements of order 3, so 3 cannot divide h_ord!
                if 2 * k_max + 1 <= m and m == 5 and h_ord % 3 == 0:
                    continue

                # 3. Sylow normalizer check for primes p > m/2 (kills e.g. S_6 h=45, S_7/A_7/A_8 hits)
                if not sylow_large_prime_compatible_in_sm(m, h_ord):
                    continue

                # 4. Jordan-Bochert prime-cycle cap
                if 2 * k_max + 1 <= m and not lemma_9_7_jordan_bochert_passes(m, h_ord):
                    continue

                # 5. If 2 * k_max + 1 <= m (no 3-cycles in H) and m in {6, 7, 8}:
                #    check Lemma 9.5 (dagger) bound on H (since H cap (C_{(3)} cup C_2) = empty
                #    whenever C_2 <= Lambda^2, which holds for ALL k_max >= 1 at m >= 4!)
                if 2 * k_max + 1 <= m and m >= 4:
                    if h_ord > lemma_9_5_dagger_bound(m):
                        continue

                raise AssertionError(f"Unhandled survivor at m={m}, {g_kind}, ks={ks}, h={h_ord}")
    return {"small_div_hits_5_to_8": div_hits}


def verify_aut_a6_and_small_lie_groups() -> Dict[str, int]:
    """Exhaustively verify zero Bol folders across the full Aut(A_6) = PGammaL_2(9) lattice
    AND small Lie-type groups PSL_2(7) ~= PSL_3(2), PGL_2(7), and PSL_2(8) (with Aut = PGammaL_2(8)).
    """
    # 1. Full Aut(A_6) = PGammaL_2(9) lattice on P^1(F_9) (deg 10)
    def f9_add(x: int, y: int) -> int:
        return ((x % 3 + y % 3) % 3) + 3 * (((x // 3) + (y // 3)) % 3)

    def f9_mul(x: int, y: int) -> int:
        a, b = x % 3, x // 3
        c, d = y % 3, y // 3
        return ((a * c + 2 * b * d) % 3) + 3 * ((a * d + b * c) % 3)

    f9_inv = [0] * 9
    for z in range(1, 9):
        for w in range(1, 9):
            if f9_mul(z, w) == 1:
                f9_inv[z] = w
                break

    g_trans = tuple(f9_add(z, 1) if z < 9 else 9 for z in range(10))
    g_scal = tuple(f9_mul(4, z) if z < 9 else 9 for z in range(10))
    g_scal_sq = compose(g_scal, g_scal)
    g_inv = tuple((9 if z == 0 else (0 if z == 9 else f9_mul(2, f9_inv[z]))) for z in range(10))
    g_frob = tuple(((z % 3) + 3 * ((2 * (z // 3)) % 3)) if z < 9 else 9 for z in range(10))
    aut9_gens = [g_trans, g_scal, g_inv, g_frob]

    total_tested = 0
    for lbl, gens in (
        ("A_6", [g_trans, g_scal_sq, g_inv]),
        ("PGL_2(9)", [g_trans, g_scal, g_inv]),
        ("S_6", [g_trans, g_scal_sq, g_inv, g_frob]),
        ("M_10", [g_trans, g_scal_sq, g_inv, compose(g_scal, g_frob)]),
        ("PGammaL_2(9)", aut9_gens),
    ):
        total_tested += verify_group_has_no_bol_folder_via_lambda2(10, gens, aut9_gens, lbl)

    # 2. PSL_2(7) ~= PSL_3(2) (order 168) and PGL_2(7) = Aut(PSL_2(7)) (order 336) on P^1(F_7) (deg 8)
    t7 = cycles_to_perm(8, [[0, 1, 2, 3, 4, 5, 6]])
    m7_pgl = cycles_to_perm(8, [[1, 3, 2, 6, 4, 5]])  # x -> 3x mod 7
    m7_psl = compose(m7_pgl, m7_pgl)  # x -> 2x mod 7
    inv7 = cycles_to_perm(8, [[0, 7], [1, 6], [2, 3], [4, 5]])  # x -> -1/x mod 7
    total_tested += verify_group_has_no_bol_folder_via_lambda2(
        8, [t7, m7_psl, inv7], [t7, m7_pgl, inv7], "PSL_2(7)"
    )
    total_tested += verify_group_has_no_bol_folder_via_lambda2(
        8, [t7, m7_pgl, inv7], [t7, m7_pgl, inv7], "PGL_2(7)"
    )

    # 3. PSL_2(8) (order 504) inside Aut(PSL_2(8)) = PGammaL_2(8) (order 1512) on P^1(F_8) (deg 9)
    # F_8 = F_2[x]/(x^3 + x + 1): generator alpha = 2 (010), powers mod 0b1011
    f8_pow = [1]
    for _ in range(7):
        v = f8_pow[-1] << 1
        if v & 8:
            v ^= 0b1011
        f8_pow.append(v)
    f8_log = {f8_pow[i]: i for i in range(7)}

    def f8_mul(a: int, b: int) -> int:
        if a == 0 or b == 0:
            return 0
        return f8_pow[(f8_log[a] + f8_log[b]) % 7]

    t8 = tuple((z ^ 1) if z < 8 else 8 for z in range(9))
    m8 = tuple(f8_mul(2, z) if z < 8 else 8 for z in range(9))
    inv8 = tuple((8 if z == 0 else (0 if z == 8 else f8_pow[(7 - f8_log[z]) % 7])) for z in range(9))
    frob8 = tuple(f8_mul(z, z) if z < 8 else 8 for z in range(9))
    total_tested += verify_group_has_no_bol_folder_via_lambda2(
        9, [t8, m8, inv8], [t8, m8, inv8, frob8], "PSL_2(8)"
    )

    return {"tested_generating_unions": total_tested}


def verify_theorem_9_regimes_9_to_45() -> Dict[str, int]:
    """Verify m = 9 Regime I, R(10) & R(11) < 1, m in {42..45} simplex base cases,
    and all 208 Regime II divisibility hits across 9 <= m <= 41.
    """
    sizes_9 = [involution_class_size_sm(9, k) for k in range(5)]
    s9_reg1_hits = 0
    a9_reg1_h_orders: List[int] = []
    for g_kind in ("A_9", "S_9"):
        g_ord = math.factorial(9) // (2 if g_kind == "A_9" else 1)
        for mask in range(1, 1 << 5):
            ks = [k for k in range(5) if (mask >> k) & 1]
            if max(ks) < 2:
                continue
            parities = {k % 2 for k in ks}
            if g_kind == "A_9" and len(parities) != 1:
                continue
            if g_kind == "S_9" and len(parities) != 2:
                continue
            lam_sz = sum(sizes_9[k] for k in ks)
            if 2 < lam_sz < g_ord and g_ord % lam_sz == 0:
                if g_kind == "S_9":
                    s9_reg1_hits += 1
                else:
                    a9_reg1_h_orders.append(g_ord // lam_sz)
    assert s9_reg1_hits == 0
    assert sorted(a9_reg1_h_orders) == [140, 144, 192, 480]
    assert all(h % 2 == 0 for h in a9_reg1_h_orders)

    for m in (10, 11):
        lhs = total_involutions_and_id_sm(m) * 2 * (3 ** ((m - 1) // 2))
        assert lhs < math.factorial(m)

    for m in (42, 43, 44, 45):
        q = m // 4
        rhs_m_times_4 = (m - 2) * (1 << q) * math.factorial(q) * math.factorial(m - 2 * q)
        c_m2 = (m + 1) // 2
        c_m3 = (m + 2) // 3
        c_m4 = (m + 3) // 4
        c_m5 = (m + 4) // 5
        v1 = 2 * (1 << c_m5) * math.factorial(c_m2) * math.factorial(c_m5)
        v2 = 2 * (4**m) * math.factorial(c_m5)
        v3 = 2 * (1 << c_m2) * math.factorial(c_m2)
        v4 = 2 * (24**c_m4) * math.factorial(c_m3)
        assert 4 * max(v1, v2, v3, v4) < rhs_m_times_4

    total_hits = 0
    killed_dagger = 0
    killed_lem96 = 0
    killed_lem97 = 0
    survivors: List[Tuple[str, int, Tuple[int, ...], int]] = []

    for m in range(9, 42):
        q = m // 4
        sizes = [involution_class_size_sm(m, k) for k in range(q)]
        dag_bound: int | None = None

        for g_kind in ("A_m", "S_m"):
            g_ord = math.factorial(m) // (2 if g_kind == "A_m" else 1)
            for mask in range(1, 1 << q):
                ks = tuple(k for k in range(q) if (mask >> k) & 1)
                k_max = ks[-1]
                if k_max < 1:
                    continue
                parities = {k % 2 for k in ks}
                if g_kind == "A_m" and len(parities) != 1:
                    continue
                if g_kind == "S_m" and len(parities) != 2:
                    continue
                lam_sz = sum(sizes[k] for k in ks)
                if lam_sz <= 2 or lam_sz >= g_ord or g_ord % lam_sz != 0:
                    continue
                total_hits += 1
                h_ord = g_ord // lam_sz

                if dag_bound is None:
                    dag_bound = lemma_9_5_dagger_bound(m)
                if h_ord > dag_bound:
                    killed_dagger += 1
                    continue

                s2_cap = lemma_9_6_sylow2_cap(m, k_max) * (2 if g_kind == "S_m" else 1)
                if (h_ord & -h_ord) > s2_cap:
                    killed_lem96 += 1
                    continue

                if not lemma_9_7_jordan_bochert_passes(m, h_ord):
                    killed_lem97 += 1
                    continue

                survivors.append((g_kind, m, ks, h_ord))

    assert total_hits == 208
    assert survivors == [("S_m", 11, (0, 1), 712_800)]
    assert 712_800 > (math.factorial(11) // math.factorial(6)) == 55_440

    return {
        "total_hits_9_to_41": total_hits,
        "killed_dagger": killed_dagger,
        "killed_lem96": killed_lem96,
        "killed_lem97": killed_lem97,
        "survivors": len(survivors),
    }


def verify_su3_4_outer_field_centralizer() -> int:
    """Verify directly over F_4 that C_{SU_3(4)}(phi_0) = {A in SL_3(F_4) : A^T A = I_3}
    has exact order 60 = 4 * (4^2 - 1) (= |SL_2(4)| on v_0^perp).
    """
    mul4 = [
        [0, 0, 0, 0],
        [0, 1, 2, 3],
        [0, 2, 3, 1],
        [0, 3, 1, 2],
    ]

    def dot3(u: Tuple[int, int, int], v: Tuple[int, int, int]) -> int:
        return mul4[u[0]][v[0]] ^ mul4[u[1]][v[1]] ^ mul4[u[2]][v[2]]

    def det3(c0: Tuple[int, int, int], c1: Tuple[int, int, int], c2: Tuple[int, int, int]) -> int:
        t0 = mul4[c0[0]][mul4[c1[1]][c2[2]] ^ mul4[c1[2]][c2[1]]]
        t1 = mul4[c0[1]][mul4[c1[0]][c2[2]] ^ mul4[c1[2]][c2[0]]]
        t2 = mul4[c0[2]][mul4[c1[0]][c2[1]] ^ mul4[c1[1]][c2[0]]]
        return t0 ^ t1 ^ t2

    unit_vecs = [
        (a, b, c)
        for a in range(4)
        for b in range(4)
        for c in range(4)
        if dot3((a, b, c), (a, b, c)) == 1
    ]
    count = 0
    for c0 in unit_vecs:
        for c1 in unit_vecs:
            if dot3(c0, c1) != 0:
                continue
            for c2 in unit_vecs:
                if dot3(c0, c2) == 0 and dot3(c1, c2) == 0 and det3(c0, c1, c2) == 1:
                    count += 1
    assert count == 60
    return count


