#ifdef NDEBUG
#error "This certificate requires assertions."
#endif

using Perm = std::string;
constexpr int degree = 170;

Perm identity() {
    Perm p(degree, 0);
    std::iota(p.begin(), p.end(), 0);
    return p;
}

Perm multiply(const Perm& a, const Perm& b) {
    Perm p(degree, 0);
    for (int i = 0; i < degree; ++i)
        p[i] = a[static_cast<unsigned char>(b[i])];
    return p;
}

Perm inverse(const Perm& a) {
    Perm p(degree, 0);
    for (int i = 0; i < degree; ++i)
        p[static_cast<unsigned char>(a[i])] = static_cast<char>(i);
    return p;
}

Perm parse(const std::string& text) {
    Perm p = identity();
    std::vector<int> cycle;
    int value = 0;
    bool inside = false;
    for (unsigned char ch : text) {
        if (std::isdigit(ch)) {
            value = value * 10 + ch - '0';
        } else if (ch == '(') {
            assert(!inside);
            inside = true;
            cycle.clear();
            value = 0;
        } else if ((ch == ',' || ch == ')') && inside) {
            assert(value >= 1 && value <= degree);
            cycle.push_back(value - 1);
            value = 0;
            if (ch == ')') {
                for (std::size_t i = 0; i < cycle.size(); ++i)
                    p[cycle[i]] = static_cast<char>(cycle[(i + 1) % cycle.size()]);
                inside = false;
            }
        }
    }
    assert(!inside);
    auto sorted = p;
    std::sort(sorted.begin(), sorted.end(), [](unsigned char a, unsigned char b) { return a < b; });
    assert(sorted == identity());
    return p;
}

