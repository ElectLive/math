"""Independent combinatorial/physical controls; not an enumeration of Bol loops."""
from itertools import product
from math import prod

def isprime(m):return m>1 and all(m%p for p in range(2,int(m**.5)+1))
def ordmod(x,q):return next(k for k in range(1,q) if pow(x,k,q)==1)
pr=[p for p in range(3,1054,2) if isprime(p)]
# Enumerate all prime-multiset products, instead of running trial division on the interval.
def rec(cur,fac,j):
    yield cur,fac
    for idx in range(j,len(pr)):
        p=pr[idx]
        if cur*p>1053:break
        yield from rec(cur*p,fac+(p,),idx)
facts=dict(rec(1,(),0));assert set(facts)==set(range(1,1054,2))
initial=[]
for n,fac in facts.items():
    w=sorted(((fac.count(p),p) for p in set(fac)),reverse=True)
    if len(w)<2 or w[0][0]<3:continue
    if len(w)==2 and w[1][0]==1:
        (a,p),(_,q)=w
        if q<p or a<p+1 or (a==p+1 and ordmod(p,q)!=p):continue
    initial.append(n)
assert sorted(initial)==[675,945,1053]
print('526 odd candidate orders >1 by generative prime-multiset sieve; survivors',sorted(initial))
def ag(i):
    return 3**i*prod(3**i-3**j for j in range(i))
def comps(s):
    if s==0:yield ();return
    for a in range(1,s+1):
        for u in comps(s-a):yield (a,)+u
def envelope(c):
    g=1
    for e in c:g=g**(3**e)*ag(e)
    return g
vals=[]
for i in range(1,5):
    admiss=list(comps(i));v=[c for c in admiss if envelope(c)%5==0]
    assert v==([] if i<4 else [(4,)])
    vals.append((3**i,len(admiss),len(v)))
print('affine/imprimitive envelope chains (degree, number, multiples of 5):',vals)
# Natural D10-module in characteristic 3: actual augmentation vectors of the cyclic site set.
# A nonzero rank-two minus space is consistent with faithful nontrivial A centralized by Y but not by t.
E=tuple(v for v in product(range(3),repeat=5) if sum(v)%3==0);O=(0,)*5
def rot(x,h=1):return tuple(x[(i-h)%5] for i in range(5))
def rev(x):return tuple(x[(-i)%5] for i in range(5))
def neg(x):return tuple(-s%3 for s in x)
def plus(x,y):return tuple((s+t)%3 for s,t in zip(x,y))
def minus(x,y):return plus(x,neg(y))
assert len(E)==81 and sum(rev(x)==neg(x) for x in E)==9 and all(rev(rot(rev(x)))==rot(x,-1) for x in E)
assert len({minus(rot(x),x) for x in E})==81 and any(rot(x)!=x for x in E)
print('genuine rational D10 augmentation: 81 points, 9 reflection-negative vectors; C5 central in odd rotations but inverted by the reflection')
# D=(V:C5) × C3, N=V × C3. Act on 3 points by the C3 factor, and independently on 81 points
# by the affine factor. Joint action faithful; individual actions not. All 81 complements of N
# have the same V-valued commutator, invisible on 3 points, very visible on 81. Not a Bol folder.
def affine_table(t,h,y):return plus(t,rot(y,h))
def interfix(t):return [y for y in E if affine_table(t,1,y)==y]
maps={};S={}
for b in E:
    t=minus(b,rot(b));m=tuple(E.index(affine_table(t,1,y)) for y in E)
    assert interfix(t)==[b];maps[b]=m
    # [u,C_b] generated by differences between affine images of translated points, independent of b.
    span={minus(minus(affine_table(t,1,u),affine_table(t,1,O)),u) for u in E}
    assert span==set(E);S[b]=span
assert len(set(maps.values()))==81
pairs={(tuple((i+q)%3 for i in range(3)),tuple(E.index(affine_table(v,h,y)) for y in E)) for v in E for h in range(5) for q in range(3)}
assert len(pairs)==1215 and len({b for a,b in pairs})==405 and len({a for a,b in pairs})==3
print('genuine paired permutation control: 1215 group elements; one action sees 3, the other 405; all 81 distinct Sylow-5 subgroups have the same size-81 commutator, invisible on 3 sites but not on 81')
