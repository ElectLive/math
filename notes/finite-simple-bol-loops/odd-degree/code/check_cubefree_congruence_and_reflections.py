def canonicalize(eq):
    r={}
    return tuple(r.setdefault(x,len(r)) for x in eq)
def native(path):
    data=Path(path).read_bytes(); assert sha256(data).hexdigest()=='5d3a7c768043e044bd644ffbee89bb62e36a6977d9c295c00d5bc555d13c5795'
    T=[list(map(int,l.split(b','))) for l in data.splitlines()]; n=len(T)
    # Congruence closure under both families of translations, on the literal table.
    trans=T+list(zip(*T))
    def closure(generators):
        p=list(range(n))
        def find(x):
            while x!=p[x]:
                p[x]=p[p[x]];x=p[x]
            return x
        queue=list(generators)
        while queue:
            x,y=queue.pop()
            if (a:=find(x))==(b:=find(y)): continue
            p[a]=b
            queue.extend((D[x],D[y]) for D in trans)
        return canonicalize(map(find,range(n)))
    one=tuple(range(n));P={one}; principals=set()
    for x in range(1,n):principals.add(closure([(0,x)]))
    P.update(principals)
    # Every congruence is generated by pairs in its identity class, since the
    # translations induce bijections on each quotient; enumerate all joins.
    todo=list(P)
    while todo:
        a=todo.pop()
        for b in principals:
            c=closure([(0,i) for i in range(1,n) if a[i]==0 or b[i]==0])
            if c not in P:P.add(c);todo.append(c)
    sizes=Counter(n//len(set(c)) for c in P)
    assert sum(T[T[i][j]][k]!=T[i][T[j][k]] for i,j,k in product(range(n),repeat=3))>0
    assert sizes[7]==1 and sizes[9]==0 and sizes[21]>=1
    def ker(c):return {i for i,x in enumerate(c) if x==0}
    c7=next(c for c in P if len(ker(c))==7)
    c21=next(c for c in P if len(ker(c))==21 and ker(c7)<ker(c))
    chain=[one,c7,c21,tuple([0]*n)]
    degrees=[]
    for a,b in zip(chain,chain[1:]):
        B=ker(b); I=sorted({a[x] for x in B});rep={i:next(x for x in B if a[x]==i) for i in I}
        table={(a[u],a[v]):a[T[u][v]] for u in B for v in B}
        assert all(a[T[u][v]]==table[a[u],a[v]] for u in B for v in B)
        assert all(table[i,j]==table[j,i] for i,j in product(I,repeat=2))
        assert all(table[table[i,j],k]==table[i,table[j,k]] for i,j,k in product(I,repeat=3))
        degrees.append(len(I))
    print('native 63 table: identity-class orders and multiplicities',sorted(sizes.items()),'normal-in-ORIGINAL factor degrees',degrees,'nonassociative')

def mul(a,b,p):
    u,v,w,x=a;y,z,t,s=b
    return (u*y+v*t)%p,(u*z+v*s)%p,(w*y+x*t)%p,(w*z+x*s)%p
def diag2(p):
    I=(1,0,0,1)
    R=[(a,b,c,(-a)%p) for a,b,c in product(range(p),repeat=3) if (a*a+b*c)%p==1]
    assert len(R)==p*(p+1)
    def lines(a):
        return {t for t in range(p) if (a[2]+a[3]*t-(a[0]+a[1]*t)*t)%p==0}|({p} if a[1]==0 else set())
    L={a:lines(a) for a in R};odds=Counter();reducible_p=0
    for a,b in combinations(R,2):
        x=mul(a,b,p); y=x;j=1
        while y!=I:y=mul(y,x,p);j+=1
        if j%2==0:continue
        d=j
        while d>1:
            q=next(e for e in range(2,d+1) if d%e==0)
            if not L[a]&L[b]:assert q<p
            if q==p: assert L[a]&L[b];reducible_p+=1
            while d%q==0:d//=q
        if not L[a]&L[b]:odds[j]+=1
    return list(sorted(odds.items())),reducible_p

def monomial():
    # Encoding signed F3 coordinate permutation with +/- index images.
    one=(1,2,3)
    def mm(a,b):return tuple(a[abs(i)-1]*(1 if i>0 else -1) for i in b)
    perm=tuple(permutations(one));allG={tuple(a*s for a,s in zip(u,v)) for u in perm for v in product([1,-1],repeat=3)}
    def act(M,x):
        y=[0]*3
        for i,j in enumerate(M):y[abs(j)-1]=x[i]*(1 if j>0 else -1)%3
        return tuple(y)
    vectors=list(product(range(3),repeat=3));refs=[g for g in allG if sum(act(g,v)==v for v in vectors)==9 and mm(g,g)==one]
    assert len(refs)==9
    groups=set()
    for mask in range(1<<len(refs)):
        R=[v for j,v in enumerate(refs) if mask>>j&1];G={one};todo=[one]
        while todo:
            a=todo.pop()
            for b in R:
                v=mm(a,b)
                if v not in G: G.add(v);todo.append(v)
        if len({tuple(map(abs,g)) for g in G})==6:groups.add(frozenset(G))
    full=[g for g in groups if len(g)%4==2]
    assert full and all(len(g)==6 for g in full)
    assert all(any(any(v) and all(act(a,v)==v for a in g) for v in vectors) for g in full)
    print('all 512 subsets of the 9 prime-field ternary monomial reflections: S3 permutation image subgroup orders', sorted(Counter(map(len,groups)).items()),'odd-index-two cases',len(full),'all fix nonzero vector')
if __name__=='__main__':
    native(sys.argv[1])
    for p in (3,5,7,11,13):print('F_%d true distinct GL2 reflection pairs: (irreducible odd rotation orders / counts, p-rotation reducible count)'%p,diag2(p))
    monomial()
