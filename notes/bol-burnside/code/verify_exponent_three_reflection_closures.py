#!/usr/bin/env python3
"""Exact signed group of a genuinely non-automorphic native mark set, and an honest nonassociative Moufang reflection closure."""
from itertools import product
import numpy as np
def code(x):return sum((j%3)*3**i for i,j in enumerate(x))
H=[(x%3,(x//3)%3,x//9) for x in range(27)]
def hp(x,y):
 a,b,c=H[x];d,e,f=H[y];return code((a+d,b+e,c+f+a*e))
def inv(x):
 a,b,c=H[x];return code((-a,-b,-c+a*b))
def gp(x,y):
 a,b,k=x;c,d,j=y
 if k:c,d=d,c
 return hp(a,c),hp(b,d),k^j
def closure(seed,op,one):
 S={one};Q=[one]
 for x in Q:
  for a in seed:
   y=op(a,x)
   if y not in S:S.add(y);Q.append(y)
 return S
def signed():
 zero=(0,0,0);t=(0,0,1);S=[(x,inv(x),0) for x in range(27)];D=[gp(t,a) for a in S]
 star=lambda x,y:gp(x,gp(y,x))
 assert any(inv(hp(x,y))!=hp(inv(x),inv(y)) for x,y in product(range(27),repeat=2))
 for seed in [D,[t,D[1],D[3]]]:
  E=set(seed)
  while True:
   F={star(d,e) for d,e in product(E,repeat=2)}
   if F==E:break
   E=F
  W=closure(seed,gp,zero);T={gp(t,e) for e in E};P=closure(T,gp,zero)
  C={w for w in W if all(gp(w,d)==gp(d,w) for d in E)}
  assert C=={w for w in W if all(gp(w,a)==gp(a,w) for a in W)}
  for d,e in product(E,repeat=2):
   h=gp(d,e)
   assert gp(h,gp(h,h))==zero and (h==zero)==(d==e)
   assert star(d,e)==star(e,d)
  assert T<={w for w in W if w[-1]==0} and len(P)*2==len(W)
  assert P=={x for x in W if x[-1]==0} and len({g[0] for g in P})==27
  assert len(C)==3
  print('UT3 native translations',len(seed),'marked reflections in closure',len(E),'true full signed group',len(W),'action on reflection closure',len(W)//len(C),'invisible central kernel',len(C),'even 3-group',len(P),'actual projection',len({g[0] for g in P}))
 assert len(set(inv(x) for x in range(27)))==27

def zassenhaus():
 X=[(i%3,(i//3)%3,(i//9)%3,(i//27)%3) for i in range(81)]
 def add(x,y):
  a,b,c,z=X[x];d,e,f,w=X[y]
  return code((a+d,b+e,c+f,z+w+(a-d)*(b*f-c*e)))
 A=np.array([[add(x,y) for y in range(81)] for x in range(81)]);I=np.arange(81);J=A[I,I];O=np.zeros(81,dtype=int);S=J[A]
 assert np.array_equal(A,A.T) and np.array_equal(A[0],I) and np.array_equal(A[I,J],O)
 assert np.array_equal(np.sort(A,axis=1),np.tile(I,(81,1)))
 bad=0
 for x in range(81):
  assert np.array_equal(A[J[x],A],A[A[x][:,None],A[x][None,:]])
  assert np.array_equal(S[x,S],S[S[x][:,None],S[x][None,:]])
  assert np.array_equal(S[x,S[x]],I)
  bad+=np.count_nonzero(A[x,A]!=A[A[x],:])
 assert bad>0
 # Generate just 0 and the three visible directions in the actual reflection geometry.
 G=np.array([0,1,3,9])
 while True:
  U=np.unique(S[G[:,None],G[None,:]])
  if len(G)==len(U):break
  G=U
 assert len(G)==81
 print('Nonassociative CML of exponent three: native points',len(X),'reflections generated by anchor and 3 marks',len(G),'Moufang/Steiner-distributivity triples each',81**3,'associative law failures',bad)
if __name__=='__main__':
 signed();zassenhaus();print('PASS: nontrivial central kernel and nonaffine ternary geometry; finite controls, not a proof for all loops.')
